def insert_params(text: str, bullets: list[str]) -> str:
    block = SPB5_HEADER + "\n".join(f"- {b}" for b in bullets) + "\n\n"
    m = re.search(r"\n(?:\*\*)?Требования к усилению:", text)
    if not m:
        if not text.endswith("\n"):
            text += "\n"
        return text + "\n" + block
    return text[: m.start()] + "\n\n" + block + text[m.start() + 1 :]


def write_md(name: str, body: str) -> None:
    path = OUT / name
    text = body.rstrip() + "\n"
    text = re.sub(r"[ \t]+\n", "\n", text)
    path.write_text(text, encoding="utf-8")
    print("wrote", name)


def measure_page(
    goal: str,
    regs: list[str] | None,
    rows: list[tuple[str, str, str]],
    params: list[str],
    enhancements: list[str] | None,
    code: str,
    k3: str,
    k2: str,
    k1: str,
    enh_row: str,
    docs_label: str = "Регламентирование",
) -> str:
    if regs:
        reg = (
            f"**{docs_label}**: В эксплуатационной документации для СПО должны быть определены:\n\n"
            + "\n".join(f"- {r}" for r in regs)
        )
    else:
        reg = f"**{docs_label}**: Не предъявляются."
    table = [
        "",
        "Описание реализации, действий и результатов при испытаниях:",
        "",
        "| Требование | Действие | Результат |",
        "|------------|----------|-----------|",
    ]
    for req, act, res in rows:
        table.append(f"| {req} | {act} | {res} |")
    param = (
        "\n\n"
        + SPB5_HEADER
        + "\n".join(f"- {p}" for p in params)
        + "\n\nТребования к усилению:\n"
    )
    if enhancements:
        enh = "\n".join(f"{i}) {e}" for i, e in enumerate(enhancements, 1))
    else:
        enh = "Не предъявляются."
    klass = (
        "\n\n| Мера защиты информации | К3 | К2 | К1 |\n"
        "|------------------------|----|----|-----|\n"
        f"| {code} | {k3} | {k2} | {k1} |\n"
        f"| Усиление {code} | {enh_row} |\n"
    )
    return (
        f"**Цель**: {goal}\n\n{reg}\n"
        + "\n".join(table)
        + param
        + "\n"
        + enh
        + klass
    )


